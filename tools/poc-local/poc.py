def ensure_registry() -> None:
    running = run("docker", "ps", "-a", "--filter", f"name=^{REGISTRY}$", "--format", "{{.Names}}", capture=True).strip()
    if not running:
        log("setup", "starting the local image registry")
        run("docker", "run", "-d", "--restart=always", "-p", f"127.0.0.1:{REGISTRY_PORT}:5000", "--name", REGISTRY, REGISTRY_IMAGE, quiet=True)
    else:
        run("docker", "start", REGISTRY, quiet=True)


def ensure_cluster(kind: str) -> None:
    clusters = run(kind, "get", "clusters", capture=True, check=False).split()
    if CLUSTER not in clusters:
        log("setup", "creating the local Kubernetes cluster (kind)")
        run(kind, "create", "cluster", "--name", CLUSTER, "--image", NODE_IMAGE, "--config", str(POC / "kind-config.yaml"), "--wait", "180s", quiet=True)
    hosts = f'server = "http://{REGISTRY}:5000"\n[host."http://{REGISTRY}:5000"]\n  capabilities = ["pull", "resolve"]\n'
    for name in (f"localhost:{REGISTRY_PORT}", REGISTRY_ALIAS):
        run("docker", "exec", NODE, "mkdir", "-p", f"/etc/containerd/certs.d/{name}", quiet=True)
        run("docker", "exec", "-i", NODE, "sh", "-c", f"cat > /etc/containerd/certs.d/{name}/hosts.toml <<'EOF'\n{hosts}EOF", quiet=True)
    run("docker", "network", "connect", "kind", REGISTRY, check=False, quiet=True)


def model_image() -> str:
    cache = STATE_DIR / "cache"
    cache.mkdir(parents=True, exist_ok=True)
    gguf = cache / "Qwen3-0.6B-Q8_0.gguf"
    if not gguf.exists() or sha256_file(gguf) != GGUF_SHA256:
        log("setup", "downloading the pinned Qwen3-0.6B weights (about 640 MB, once)")
        run("curl", "-fL", "--retry", "3", "-o", str(gguf), GGUF_URL, quiet=True)
        if sha256_file(gguf) != GGUF_SHA256:
            gguf.unlink()
            fail("downloaded weights do not match the pinned sha256")
    build = STATE_DIR / "build"
    shutil.rmtree(build, ignore_errors=True)
    build.mkdir(parents=True)
    shutil.copy(POC / "model-image" / "Dockerfile", build / "Dockerfile")
    os.link(gguf, build / "model.gguf")
    tag = f"localhost:{REGISTRY_PORT}/infercrane-poc/qwen3-0.6b-q8:{MODEL_REVISION[:12]}"
    log("setup", "building the model server image (pinned llama.cpp + pinned weights)")
    run("docker", "build", "-q", "--build-arg", f"BASE={LLAMA_BASE}", "-t", tag, str(build), quiet=True)
    run("docker", "push", "-q", tag, quiet=True)
    pushed = run("docker", "inspect", "--format", "{{index .RepoDigests 0}}", tag, capture=True).strip()
    if "@sha256:" not in pushed:
        fail(f"could not read a registry digest for {tag}")
    return f"{REGISTRY_ALIAS}/infercrane-poc/qwen3-0.6b-q8@{pushed.split('@', 1)[1]}"


def quantized_image() -> str | None:
    """Generates a 4-bit model from the pinned 8-bit weights with llama.cpp's quantizer."""
    tool = shutil.which("llama-quantize")
    if not tool:
        log("setup", "llama-quantize not found: skipping the generated 4-bit model (brew install llama.cpp)")
        return None
    cache = STATE_DIR / "cache"
    source, target = cache / "Qwen3-0.6B-Q8_0.gguf", cache / "Qwen3-0.6B-Q4_K_M-generated.gguf"
    if not target.exists():
        log("setup", "generating a 4-bit model from the pinned 8-bit weights (llama-quantize Q4_K_M)")
        run(tool, "--allow-requantize", str(source), str(target), "Q4_K_M", quiet=True)
    save({"generated_model_sha256": sha256_file(target)})
    build = STATE_DIR / "build-q4"
    shutil.rmtree(build, ignore_errors=True)
    build.mkdir(parents=True)
    shutil.copy(POC / "model-image" / "Dockerfile", build / "Dockerfile")
    os.link(target, build / "model.gguf")
    tag = f"localhost:{REGISTRY_PORT}/infercrane-poc/qwen3-0.6b-q4-generated:{MODEL_REVISION[:12]}"
    run("docker", "build", "-q", "--build-arg", f"BASE={LLAMA_BASE}", "-t", tag, str(build), quiet=True)
    run("docker", "push", "-q", tag, quiet=True)
    pushed = run("docker", "inspect", "--format", "{{index .RepoDigests 0}}", tag, capture=True).strip()
    return f"{REGISTRY_ALIAS}/infercrane-poc/qwen3-0.6b-q4-generated@{pushed.split('@', 1)[1]}"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()



def port_forward(required: bool = True) -> bool:
    previous = state().get("port_forward_pid")
    if previous:
        try:
            os.kill(previous, 0)
            return True
        except OSError:
            pass
    log_file = (STATE_DIR / "port-forward.log").open("w")
    process = subprocess.Popen(["kubectl", "--context", CONTEXT, "-n", NAMESPACE, "port-forward", "svc/infercrane", f"{API_PORT}:8080"], stdout=log_file, stderr=subprocess.STDOUT, start_new_session=True)
    save({"port_forward_pid": process.pid})
    for _ in range(60):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{API_PORT}/readyz", timeout=2) as response:
                if response.status == 200:
                    return True
        except Exception:  # noqa: BLE001 - still starting
            time.sleep(1)
    if required:
        fail("the control plane did not become reachable on the port-forward")
    return False


def up() -> None:
    for tool in ("docker", "kubectl", "go", "curl"):
        if not shutil.which(tool):
            fail(f"{tool} is required")
    current = state()
    if not current.get("api_key"):
        save({"api_key": secrets.token_hex(24)})
    kind = kind_binary()
    ensure_registry()
    ensure_cluster(kind)
    run("sh", str(POC / "simulated-accelerator.sh"), CONTEXT, NODE, ACCELERATOR_RESOURCE, ACCELERATOR_LABEL, ACCELERATOR, "6", quiet=True)
    log("setup", f"node advertises 6 x {ACCELERATOR_RESOURCE} ({ACCELERATOR}: CPU only, for scheduling)")
    image = model_image()
    save({"model_image": image})
    quantized = quantized_image()
    if quantized:
        save({"model_image_q4": quantized})
    log("setup", "building the control plane image")
    run("docker", "build", "-q", "--target", "runtime", "-t", CONTROL_PLANE_IMAGE, str(ROOT), quiet=True)
    run(kind, "load", "docker-image", CONTROL_PLANE_IMAGE, "--name", CLUSTER, quiet=True)
    for manifest in ("namespace.yaml", "service-accounts.yaml", "provider-rbac.yaml"):
        kubectl("apply", "-f", str(ROOT / "deploy" / "kubernetes" / "base" / manifest))
    secret = kubectl("-n", NAMESPACE, "create", "secret", "generic", "infercrane-worker", f"--from-literal=api-key={state()['api_key']}", "--dry-run=client", "-o", "json")
    subprocess.run(["kubectl", "--context", CONTEXT, "apply", "-f", "-"], input=secret, text=True, check=True, capture_output=True)
    rendered = (POC / "manifests.yaml").read_text()
    for key, value in {"POSTGRES_IMAGE": POSTGRES_IMAGE, "CONTROL_PLANE_IMAGE": CONTROL_PLANE_IMAGE, "MODEL_IMAGE": image, "ACCELERATOR_RESOURCE": ACCELERATOR_RESOURCE, "ACCELERATOR_LABEL": ACCELERATOR_LABEL, "PRICES_JSON": rate_card()}.items():
        rendered = rendered.replace(f"@@{key}@@", value)
    subprocess.run(["kubectl", "--context", CONTEXT, "apply", "-f", "-"], input=rendered, text=True, check=True, capture_output=True)
    log("setup", "starting Postgres and the InferCrane control plane in the cluster")

def service_for(deployment_name: str) -> str:
    detail = api("GET", f"/api/v1/deployments/{deployment_name}")
    endpoints = sorted(set(re.findall(r"http://(infercrane-[0-9a-f]+)\." + NAMESPACE + r"\.svc:\d+", json.dumps(detail))))
    if not endpoints:
        fail(f"no serving endpoint recorded for {deployment_name}")
    return endpoints[0]


def evaluate(deployment_name: str) -> tuple[float, int]:
    service = service_for(deployment_name)
    process = subprocess.Popen(["kubectl", "--context", CONTEXT, "-n", NAMESPACE, "port-forward", f"svc/{service}", f":{SERVER_PORT}"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    try:
        line = process.stdout.readline()
        match = re.search(r"127\.0\.0\.1:(\d+)", line)
        if not match:
            fail(f"port-forward to {service} failed: {line}")
        port = match.group(1)
        correct = 0
        for a, b in EVAL:
            body = {"model": MODEL_ID, "temperature": 0, "max_tokens": 24, "messages": [{"role": "user", "content": f"What is {a} + {b}? Reply with only the number."}]}
            request = urllib.request.Request(f"http://127.0.0.1:{port}/v1/chat/completions", data=json.dumps(body).encode(), method="POST")
            request.add_header("Content-Type", "application/json")
            request.add_header("Authorization", f"Bearer {state()['api_key']}")
            with urllib.request.urlopen(request, timeout=120) as response:
                text = json.loads(response.read())["choices"][0]["message"].get("content") or ""
            correct += str(a + b) in re.sub(r"<think>.*?</think>", "", text, flags=re.S)
        return correct / len(EVAL), len(EVAL)
    finally:
        process.terminate()


def attach_quality(candidate: dict, control_score: float | None) -> float:
    score, samples = evaluate(candidate["deployment_name"])
    passed = score >= 0.5 if control_score is None else score >= control_score - 0.10
    result = {"schema": "infercrane.dev/evaluator-result/v2", "suite": "poc-arithmetic", "suite_version": "1", "evaluator": "tools/poc-local", "evaluator_version": "1", "score": round(score, 4), "passed": passed, "sample_count": samples, "artifact_digest": f"sha256:{GGUF_SHA256}", "evaluated_at": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")}
    path = STATE_DIR / f"quality-{candidate['id'][:12]}.json"
    path.write_text(json.dumps(result))
    key = STATE_DIR / "evaluator.key"
    if not key.exists():
        cli("evaluation", "keygen", "--file", str(key))
    signed = STATE_DIR / f"signed-{candidate['id'][:12]}-{int(time.time())}.json"
    cli("evaluation", "ingest", candidate["deployment_name"], candidate["revision_id"], "--result", str(path), "--key", str(key), "--file", str(signed), "--attach")
    log("quality", f"{candidate.get('label', candidate['id'][:8])}: {int(score * len(EVAL))} of {len(EVAL)} test answers correct → {'PASS' if passed else 'BLOCK'} (signed and attached as evidence)")
    return score


def inspect(campaign: str) -> dict:
    return json.loads(cli("optimize", "inspect", campaign, "--output", "json"))


def try_inspect(campaign: str) -> dict | None:
    """Inspect without exiting: a saturated laptop can stall one request."""
    current = state()
    env = dict(os.environ, INFERCRANE_URL=f"http://127.0.0.1:{API_PORT}", INFERCRANE_API_KEY=current["api_key"], INFERCRANE_CONTEXT="")
    try:
        completed = subprocess.run([cli_binary(), "optimize", "inspect", campaign, "--output", "json"], capture_output=True, text=True, env=env, timeout=150)
        return json.loads(completed.stdout) if completed.returncode == 0 else None
    except (subprocess.TimeoutExpired, json.JSONDecodeError):
        return None


def restart_port_forward() -> None:
    previous = state().get("port_forward_pid")
    if previous:
        try:
            os.kill(previous, signal.SIGTERM)
        except OSError:
            pass
    save({"port_forward_pid": None})
    port_forward(required=False)  # still busy is fine; the next poll tries again


def watch(campaign: str, labels: dict, timeout_s: int = 6 * 3600, unreachable_limit_s: int = 20 * 60) -> dict:
    seen: dict[str, str] = {}
    control_score: float | None = None
    measured: dict = state().get("measured", {})
    deadline = time.monotonic() + timeout_s
    unreachable_since: float | None = None
    while time.monotonic() < deadline:
        current = try_inspect(campaign)
        if current is None:
            now = time.monotonic()
            if unreachable_since is None:
                unreachable_since = now
                log("campaign", "control plane is not answering (the laptop is busy measuring); retrying")
            elif now - unreachable_since > unreachable_limit_s:
                fail(f"control plane unreachable for {unreachable_limit_s // 60} minutes; the campaign keeps running in the cluster, continue later with: make poc-local-resume")
            if now - unreachable_since > 90:
                restart_port_forward()
            time.sleep(15)
            continue
        if unreachable_since is not None:
            log("campaign", f"control plane answering again after {int(time.monotonic() - unreachable_since)} s")
            unreachable_since = None
        record = current.get("campaign", current)
        for candidate in record.get("candidates", []):
            candidate["label"] = labels.get(candidate.get("proposal_candidate_id", ""), candidate.get("id", "")[:8])
            status = candidate.get("state", "")
            if seen.get(candidate["id"]) != status:
                seen[candidate["id"]] = status
                reason = candidate.get("failure_code") or ""
                log("campaign", f"{candidate['label']}: {words(status, reason or None)}")
            already_scored = candidate["id"] in state().get("quality", {})
            if status == "validating" and not already_scored and not candidate.get("quality_evidence_id") and candidate.get("revision_id"):
                try:
                    score = attach_quality(candidate, control_score)
                except (OSError, urllib.error.URLError, json.JSONDecodeError) as error:
                    log("quality", f"{candidate['label']}: evaluation did not complete ({error}); retrying on the next poll")
                    continue
                control_score = score if control_score is None else control_score
                scores = state().get("quality", {})
                scores[candidate["id"]] = score
                save({"quality": scores})
            if candidate.get("benchmark_id") and candidate["id"] not in measured:
                row = benchmark_row(candidate)
                if row:
                    measured[candidate["id"]] = row
                    save({"measured": measured})
        state_name = record.get("state", "")
        if state_name in TERMINAL_CAMPAIGN:
            return record
        time.sleep(10)
    fail("campaign did not finish within the time limit")
    return {}


def benchmark_row(candidate: dict) -> dict | None:
    try:
        rows = api("GET", f"/api/v1/deployments/{candidate['deployment_name']}/benchmarks")
    except SystemExit:
        return None
    rows = rows.get("data", rows.get("benchmarks", [])) if isinstance(rows, dict) else rows
    row = next((r for r in rows if r.get("id") == candidate.get("benchmark_id")), None)
    if not row:
        return None
    workload_doc = row.get("workload", row.get("workload_json"))
    workload_doc = json.loads(workload_doc) if isinstance(workload_doc, str) and workload_doc else (workload_doc or {})
    return {"output_tps": row.get("output_token_throughput"), "ttft_p95_ms": row.get("ttft_p95_ms"), "latency_p95_ms": row.get("latency_p95_ms"), "comparison": ((workload_doc.get("measured") or {}).get("comparison") or {})}


def cost_per_million(tps: float | None) -> float | None:
    return None if not tps else NOMINAL_HOURLY_USD / (tps * 3600) * 1_000_000


def result_card(record: dict, labels: dict) -> list[str]:
    current = state()
    measured, scores = current.get("measured", {}), current.get("quality", {})
    rows = []
    for candidate in record.get("candidates", []):
        label = labels.get(candidate.get("proposal_candidate_id", ""), candidate["id"][:8])
        rows.append((label, candidate, measured.get(candidate["id"], {}), scores.get(candidate["id"])))
    if not rows:
        return []
    base = rows[0][2]
    winner = next((r for r in rows if r[1].get("state") == "qualified"), None)
    lines = ["Your traffic: Mooncake (Kimi) production trace replay · model Qwen3-0.6B", ""]
    for label, candidate, metrics, score in rows:
        tps = metrics.get("output_tps")
        cost = cost_per_million(tps)
        quality = "-" if score is None else f"{round(score * len(EVAL))}/{len(EVAL)}"
        lines.append(f"{label}")
        lines.append(f"   {('%.1f' % tps) if tps else '-'} tokens/s · p95 latency {('%.0f ms' % metrics['latency_p95_ms']) if metrics.get('latency_p95_ms') else '-'} · ${('%.2f' % cost) if cost else '-'} per 1M tokens · answers {quality}")
        if candidate is not rows[0][1]:
            change = ""
            if tps and base.get("output_tps"):
                change = f"{(tps / base['output_tps'] - 1) * 100:+.0f}% throughput · "
            lines.append(f"   {change}{words(candidate.get('state', ''), candidate.get('failure_code'))}")
    lines.append("")
    if winner and winner[1] is not rows[0][1]:
        lines.append(f"Decision: roll out “{winner[0]}”, measured better on your traffic with the same answers.")
    else:
        lines.append("Decision: keep your current setup. Nothing beat it by more than the measurement noise, so nothing changes in production.")
    lines.append(f"Costs use a stated laptop rate (${NOMINAL_HOURLY_USD}/h). CPU run on a laptop: this proves the process, not GPU speed.")
    lines.append("")
    lines.append(f"Audit trail: campaign {record.get('id', '')} · signed quality records attached to each revision")
    lines.append(f"Pinned: model {MODEL_ID}@{MODEL_REVISION[:12]} · server image {current.get('model_image', '').split('@')[-1][:19]}… · trace Mooncake FAST'25 sha256:{MOONCAKE_SHA256[:12]}…")
    lines.append(f"Follow it: infercrane optimize watch {record.get('id', '')} · rerun: make poc-local-run")
    return lines


def summary(record: dict, labels: dict) -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    path = OUTPUT / f"{record.get('id', 'campaign')}.json"
    path.write_text(json.dumps(record, indent=2))
    card = result_card(record, labels)
    save({"result": card})
    width = max([len(line) for line in card] + [40]) + 2
    print("\n\x1b[1m╭" + "─" * width + "╮\x1b[0m")
    print("\x1b[1m│ RESULT" + " " * (width - 7) + "│\x1b[0m")
    for line in card:
        print("\x1b[1m│\x1b[0m " + line.ljust(width - 1) + "\x1b[1m│\x1b[0m")
    print("\x1b[1m╰" + "─" * width + "╯\x1b[0m\n")
    log("result", f"full record: {path}")


def finish(campaign: str, labels: dict) -> None:
    record = watch(campaign, labels)
    qualified = [c for c in record.get("candidates", []) if c.get("state") == "qualified"]
    if qualified:
        winner = qualified[0]
        cli("optimize", "activate", campaign, "--candidate", winner["id"])
        log("rollout", f"activated {labels.get(winner.get('proposal_candidate_id', ''), winner['id'][:8])} as endpoint {OPTIMIZED}")
        record = inspect(campaign).get("campaign", record)
    summary(record, labels)


def resume() -> None:
    campaign = state().get("campaign")
    proposal_path = STATE_DIR / "proposal.json"
    if not campaign or not proposal_path.exists():
        fail("no campaign to resume")
    port_forward()
    doc = json.loads(proposal_path.read_text())
    labels = state().get("labels") or {candidate["id"]: candidate["configuration_profile"] for candidate in doc["candidates"]}
    log("resume", f"continuing campaign {campaign}")
    finish(campaign, labels)


def reset_previous() -> None:
    previous = state().get("campaign")
    if previous:
        try:
            record = api("GET", f"/api/v1/optimization/campaigns/{previous}")
            if record.get("campaign", record).get("state") not in TERMINAL_CAMPAIGN:
                api("POST", f"/api/v1/optimization/campaigns/{previous}/cancel", headers={"Idempotency-Key": f"cancel-{previous}"})
        except SystemExit:
            pass
    listing = api("GET", "/api/v1/deployments")
    rows = listing.get("data", listing.get("deployments", [])) if isinstance(listing, dict) else listing
    for row in rows:
        name = row.get("name") if isinstance(row, dict) else row
        if isinstance(name, str) and name.startswith(OPTIMIZED):
            cli("delete", name, "--yes", "--wait", check=False)
    save({"campaign": None, "result": None, "quality": {}, "measured": {}, "plan": None, "diagnosis": None})


def run_poc(trace: str, requests_total: int) -> None:
    if not state().get("model_image"):
        fail("run `poc.py up` first")
    port_forward()
    reset_previous()
    deploy_baseline()
    observer = Observer()
    if trace == "mooncake":
        replay_mooncake(requests_total, input_scale=32, max_output=64, spread_seconds=120)
    else:
        send_traffic(requests_total)
    chosen = plan(observer.finish())
    digest = capture_replay()
    doc = proposal(digest)
    labels = {candidate["id"]: chosen[index][0] for index, candidate in enumerate(doc["candidates"])}
    (STATE_DIR / "proposal.json").write_text(json.dumps(doc, indent=2))
    save({"labels": labels})
    campaign = campaign_create(doc)
    save({"campaign": campaign})
    approval_cap = round(NOMINAL_HOURLY_USD * 6 * len(chosen) * 1.2, 2)
    cli("optimize", "approve", campaign, "--max-cost-usd", str(approval_cap), "--expires-in", "6h")
    log("approve", f"spend approved up to ${approval_cap} (stated laptop rate ${NOMINAL_HOURLY_USD}/h), valid 6 h")
    finish(campaign, labels)



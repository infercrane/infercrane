def fail(message: str) -> None:
    print(f"\x1b[31m✗ {message}\x1b[0m", file=sys.stderr, flush=True)
    raise SystemExit(1)


def run(*command: str, capture: bool = False, check: bool = True, env: dict | None = None, timeout: float | None = None, quiet: bool = False) -> str:
    merged = dict(os.environ, **(env or {}))
    stdout = subprocess.PIPE if capture or quiet else None
    completed = subprocess.run(command, stdout=stdout, stderr=subprocess.PIPE if capture or quiet else None, text=True, env=merged, timeout=timeout)
    if check and completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip()[-1500:] if (capture or quiet) else ""
        fail(f"{' '.join(command[:4])}… exited {completed.returncode}\n{detail}")
    return completed.stdout or ""



def send_traffic(requests_total: int = 40, sessions: int = 5, workers: int = 4) -> None:
    log("traffic", f"sending {requests_total} requests in {sessions} conversations through the InferCrane gateway")
    key = state()["api_key"]

    def one(index: int) -> int:
        session = index % sessions
        body = {"model": BASELINE, "stream": False, "temperature": 0, "max_tokens": 48, "messages": [{"role": "system", "content": SYSTEM_PROMPTS[session % len(SYSTEM_PROMPTS)]}, {"role": "user", "content": f"Question {index}: briefly explain our {TOPICS[index % len(TOPICS)]}."}]}
        request = urllib.request.Request(f"http://127.0.0.1:{API_PORT}/v1/chat/completions", data=json.dumps(body).encode(), method="POST")
        for header, value in {"Authorization": f"Bearer {key}", "Content-Type": "application/json", "X-InferCrane-Session-ID": f"poc-session-{session}", "X-InferCrane-Parent-Session-ID": "poc-traffic"}.items():
            request.add_header(header, value)
        time.sleep(random.uniform(0, 0.4))
        with urllib.request.urlopen(request, timeout=300) as response:
            payload = json.loads(response.read())
        return int((payload.get("usage") or {}).get("completion_tokens", 0))

    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
        tokens = sum(pool.map(one, range(requests_total)))
    log("traffic", f"done: {tokens} output tokens reported by the server")


def mooncake_rows() -> list[dict]:
    cache = STATE_DIR / "cache" / "mooncake_trace.jsonl"
    cache.parent.mkdir(parents=True, exist_ok=True)
    if not cache.exists() or sha256_file(cache) != MOONCAKE_SHA256:
        run("curl", "-fsSL", "--retry", "3", "-o", str(cache), MOONCAKE_URL, quiet=True)
        if sha256_file(cache) != MOONCAKE_SHA256:
            cache.unlink()
            fail("downloaded Mooncake trace does not match the pinned sha256")
    return [json.loads(line) for line in cache.read_text().splitlines() if line.strip()]


def block_text(hash_id: int, tokens: int) -> list[str]:
    generator = random.Random(hash_id)
    return [generator.choice(WORDS) for _ in range(tokens)]


def replay_mooncake(requests_total: int, input_scale: int, max_output: int, spread_seconds: float, workers: int = 8) -> None:
    rows = mooncake_rows()[:requests_total]
    start, end = rows[0]["timestamp"], rows[-1]["timestamp"]
    stretch = spread_seconds / max(1.0, (end - start) / 1000)
    block = max(1, MOONCAKE_BLOCK_TOKENS // input_scale)
    log("traffic", f"replaying {len(rows)} requests from the Mooncake (Kimi) production trace: real arrival pattern and shared prefixes, inputs scaled 1/{input_scale} for a laptop CPU")
    key = state()["api_key"]
    began = time.monotonic()

    def one(row: dict) -> int:
        delay = (row["timestamp"] - start) / 1000 * stretch - (time.monotonic() - began)
        if delay > 0:
            time.sleep(delay)
        target = max(8, row["input_length"] // input_scale)
        words: list[str] = []
        for hash_id in row.get("hash_ids") or [row["timestamp"]]:
            words += block_text(hash_id, block)
        words = (words + block_text(row["timestamp"], target))[:target]
        shared, unique = words[:-block] or words[:1], words[-block:]
        body = {"model": BASELINE, "stream": False, "temperature": 0, "max_tokens": max(1, min(max_output, row["output_length"])), "ignore_eos": True,
                "messages": [{"role": "system", "content": " ".join(shared)}, {"role": "user", "content": " ".join(unique)}]}
        request = urllib.request.Request(f"http://127.0.0.1:{API_PORT}/v1/chat/completions", data=json.dumps(body).encode(), method="POST")
        session = (row.get("hash_ids") or [0])[0]
        for header, value in {"Authorization": f"Bearer {key}", "Content-Type": "application/json", "X-InferCrane-Session-ID": f"mooncake-{session}", "X-InferCrane-Parent-Session-ID": "mooncake-replay"}.items():
            request.add_header(header, value)
        try:
            with urllib.request.urlopen(request, timeout=600) as response:
                payload = json.loads(response.read())
        except (urllib.error.URLError, OSError, json.JSONDecodeError) as error:
            failures.append(str(getattr(error, "code", "")) or type(error).__name__)
            return 0
        return int((payload.get("usage") or {}).get("completion_tokens", 0))

    failures: list[str] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
        tokens = sum(pool.map(one, rows))
    note = f" · {len(failures)} of {len(rows)} requests failed ({', '.join(sorted(set(failures)))})" if failures else ""
    log("traffic", f"done: {tokens} output tokens reported by the server{note} · trace: kvcache-ai/Mooncake FAST'25 (Apache-2.0)")
    if len(failures) > len(rows) // 2:
        fail("most replayed requests failed; check the gateway and the model server before measuring")


def baseline_pod() -> str:
    service = service_for(BASELINE)
    pods = json.loads(kubectl("-n", NAMESPACE, "get", "pods", "-l", f"app.kubernetes.io/instance={service}", "-o", "json"))["items"]
    running = [p["metadata"]["name"] for p in pods if p.get("status", {}).get("phase") == "Running"]
    if not running:
        fail("the current setup has no running server to observe")
    return running[0]


def server_metrics(pod: str) -> dict:
    text = kubectl("get", "--raw", f"/api/v1/namespaces/{NAMESPACE}/pods/{pod}:{SERVER_PORT}/proxy/metrics")
    values: dict[str, float] = {}
    for line in text.splitlines():
        if line and not line.startswith("#"):
            parts = line.split()
            try:
                values[parts[0].split("{")[0]] = values.get(parts[0].split("{")[0], 0.0) + float(parts[-1])
            except (ValueError, IndexError):
                continue
    return values


class Observer:
    """Samples the current setup's server while the traffic runs."""

    def __init__(self) -> None:
        self.pod = baseline_pod()
        self.start = server_metrics(self.pod)
        self.waiting: list[float] = []
        self.stop = False
        self.thread = __import__("threading").Thread(target=self.loop, daemon=True)
        self.thread.start()

    def loop(self) -> None:
        while not self.stop:
            try:
                self.waiting.append(server_metrics(self.pod).get("llamacpp:requests_deferred", 0.0))
            except Exception:  # noqa: BLE001 - a sample can fail while the server is busy
                pass
            time.sleep(2)

    def finish(self) -> dict:
        self.stop = True
        end = server_metrics(self.pod)
        delta = lambda key: max(0.0, end.get(key, 0.0) - self.start.get(key, 0.0))  # noqa: E731
        prefill, decode = delta("llamacpp:prompt_seconds_total"), delta("llamacpp:tokens_predicted_seconds_total")
        total = prefill + decode or 1.0
        return {"prefill_share": prefill / total, "decode_share": decode / total, "waiting_mean": sum(self.waiting) / len(self.waiting) if self.waiting else 0.0,
                "waiting_peak": max(self.waiting) if self.waiting else 0.0, "prompt_tokens": delta("llamacpp:prompt_tokens_total"), "output_tokens": delta("llamacpp:tokens_predicted_total")}


def plan(diagnosis: dict) -> list:
    log("diagnose", f"while serving your traffic, the current setup spent {diagnosis['prefill_share']:.0%} of its time reading prompts and {diagnosis['decode_share']:.0%} writing answers; on average {diagnosis['waiting_mean']:.1f} requests waited in line (peak {diagnosis['waiting_peak']:.0f})")
    order = []
    if diagnosis["waiting_mean"] >= 0.5:
        order.append("queueing")
    if diagnosis["decode_share"] >= diagnosis["prefill_share"]:
        order += (["quantize"] if state().get("model_image_q4") else []) + ["decode"]
    else:
        order.append("prefill")
    for fallback in ("decode", "queueing", "prefill"):
        if len(order) >= 2:
            break
        if fallback not in order:
            order.append(fallback)
    chosen = [CONTROL]
    for key in order[:2]:
        label, profile, args, why = OPTIONS[key]
        chosen.append((label, profile, args))
        change = " ".join(args) if args else "same flags, different model image"
        log("plan", f"try “{label}”: {why}  [change: {change}]")
        if key == "quantize":
            cache = STATE_DIR / "cache"
            source, target = cache / "Qwen3-0.6B-Q8_0.gguf", cache / "Qwen3-0.6B-Q4_K_M-generated.gguf"
            if source.exists() and target.exists():
                log("artifact", f"generated Q4_K_M from the pinned Q8_0 weights: {source.stat().st_size / 1e6:.0f} MB → {target.stat().st_size / 1e6:.0f} MB, sha256:{state().get('generated_model_sha256', '')[:12]}…, pinned by image digest")
    CANDIDATES[:] = chosen
    save({"plan": [{"label": label, "args": args} for label, _, args in chosen], "diagnosis": diagnosis})
    return chosen


def capture_replay() -> str:
    output = json.loads(cli("replay", BASELINE, "--window", "1h", "--max-requests", "200", "--output", "json"))
    digest = output.get("shape_digest") or (output.get("trace") or {}).get("shape_digest") or ""
    digest = digest.removeprefix("sha256:")
    if not re.fullmatch(r"[0-9a-f]{64}", digest):
        fail(f"replay capture returned no shape digest: {json.dumps(output)[:400]}")
    summary = output.get("summary") or (output.get("trace") or {}).get("summary") or {}
    log("capture", f"traffic shape recorded without content: sha256:{digest[:12]}… {json.dumps(summary)[:160]}")
    return digest


def proposal(digest: str) -> dict:
    base = json.loads(cli("optimize", "propose", MODEL_ID, "--model-revision", MODEL_REVISION, "--provider", "kubernetes", "--gpu", ACCELERATOR, "--objective", "interactive", "--profile", "buffered", "--workload-fingerprint", f"sha256:{digest}", "--include-simulated", "--max-candidates", str(len(CANDIDATES)), "--source", "catalog", "--output", "json"))
    template = next((c for c in base.get("candidates", []) if c["deployment"]["provider"]["adapter"] == "kubernetes"), None)
    if template is None:
        fail("the planner returned no Kubernetes template candidate")
    candidates = []
    for rank, (label, profile, args) in enumerate(CANDIDATES, start=1):
        deployment = json.loads(json.dumps(template["deployment"]))
        deployment.pop("serving", None)
        deployment["name"] = OPTIMIZED
        deployment["runtime"] = {"engine": "custom-oci", "version": "llama.cpp-server-086942d6", "args": args, "workload": workload(IMAGE_FOR.get(profile, "model_image"))}
        identity = hashlib.sha256(json.dumps({"profile": profile, "deployment": deployment}, sort_keys=True).encode()).hexdigest()
        candidate = json.loads(json.dumps(template)) | {"id": identity, "rank": rank, "configuration_profile": profile, "deployment": deployment}
        candidate["features"] = [{"name": "runtime_args", "state": "candidate" if args else "baseline", "source": label}]
        candidates.append(candidate)
    base["candidates"] = candidates
    base["starting_point"] = dict(base["starting_point"], candidate_id=candidates[0]["id"])
    return base



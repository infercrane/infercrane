CREATE TABLE benchmark_results (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    deployment_id TEXT NOT NULL REFERENCES deployments(id),
    deployment_name TEXT NOT NULL,
    revision_id TEXT NOT NULL REFERENCES deployment_revisions(id),
    model_artifact_id TEXT REFERENCES model_artifacts(id),
    model_identity TEXT NOT NULL,
    runtime TEXT NOT NULL,
    runtime_version TEXT NOT NULL DEFAULT '',
    runtime_config_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    provider TEXT NOT NULL,
    region TEXT NOT NULL DEFAULT '',
    gpu TEXT NOT NULL DEFAULT '',
    compute_mode TEXT NOT NULL,
    tool TEXT NOT NULL,
    tool_version TEXT NOT NULL,
    workload_json JSONB NOT NULL,
    reproduction_command TEXT NOT NULL,
    request_count INTEGER NOT NULL CHECK (request_count > 0),
    succeeded INTEGER NOT NULL CHECK (succeeded >= 0),
    failed INTEGER NOT NULL CHECK (failed >= 0),
    duration_seconds DOUBLE PRECISION NOT NULL CHECK (duration_seconds >= 0),
    request_throughput DOUBLE PRECISION,
    output_token_throughput DOUBLE PRECISION,
    ttft_p50_ms DOUBLE PRECISION,
    ttft_p95_ms DOUBLE PRECISION,
    tpot_p50_ms DOUBLE PRECISION,
    tpot_p95_ms DOUBLE PRECISION,
    latency_p50_ms DOUBLE PRECISION,
    latency_p95_ms DOUBLE PRECISION,
    goodput DOUBLE PRECISION,
    gpu_utilization DOUBLE PRECISION,
    cost_metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (succeeded + failed <= request_count)
);

CREATE INDEX benchmark_results_deployment_created_idx
    ON benchmark_results(tenant_id, deployment_id, created_at DESC);
